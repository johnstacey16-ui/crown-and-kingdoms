import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';

const source = readFileSync(new URL('../js/simulation.js', import.meta.url), 'utf8');
const a = source.indexOf('const mv=(u,dx,dy)=>');
const b = source.indexOf('\n/* Local spatial grid', a);
assert.ok(a >= 0 && b > a, 'movement primitive exists');
const W = 10, H = 10;
const S = { wt: new Uint8Array(W * H), nd: new Array(W * H).fill(null), g: new Uint8Array(W * H) };
const mv = vm.runInNewContext(source.slice(a, b) + '\nmv', { S, W, H });
const land = { x: 1.5, y: 1.5, sh: false };
mv(land, -2, 0);
assert.equal(land.x, 1.5, 'land units cannot leave west map boundary');
mv(land, NaN, 0);
assert.equal(land.x, 1.5, 'invalid movement delta cannot corrupt coordinates');
S.wt[1 * W + 2] = 1;
mv(land, 1, 0);
assert.equal(land.x, 1.5, 'land cannot enter deep water');
S.wt[1 * W + 2] = 2;
mv(land, 1, 0);
assert.equal(land.x, 2.5, 'land can traverse shallow ford tiles');
const ship = { x: 1.5, y: 1.5, sh: true };
mv(ship, 1, 0);
assert.equal(ship.x, 2.5, 'ships can enter shallow water');
mv(ship, 1, 0);
assert.equal(ship.x, 2.5, 'ships cannot move onto dry land');
S.nd[1 * W + 3] = { k: 'fish' };
S.wt[1 * W + 3] = 1;
mv(ship, 1, 0);
assert.equal(ship.x, 2.5, 'ships cannot enter occupied fishing nodes');
console.log('movement-terrain-bounds: passed');
