test('Destroying Tidewatch Castle calls a real one-time royal reserve to guard home',()=>{
 const c=tidewatch();
 const reserveIndex=c("CAMP[14].ev.findIndex(e=>typeof e.when==='function'&&e.when.toString().includes('cmp.d.castle'))");
 assert.ok(reserveIndex>=0,'a separate story event follows the Castle milestone');
 const initial=c("S.us.filter(u=>u.t===0&&['spear','xbow'].includes(u.k)).length");
 const resources=c('JSON.stringify(S.res[0])');
 c("cmp.k=14;cmpTick(8)");
 assert.equal(c('!!cmp.e['+reserveIndex+']'),false,'royal reserve cannot arrive while the enemy Castle stands');
 c("S.bs.find(b=>b.t===1&&b.k==='castle').hp=0;cmp.k=14;cmpTick(2)");
 assert.equal(c('cmp.d.castle'),1);
 c('cmpTick(1)');
 assert.equal(c('!!cmp.e['+reserveIndex+']'),true,'Castle destruction triggers a new visible stage');
 assert.equal(c("S.us.filter(u=>u.t===0&&['spear','xbow'].includes(u.k)).length"),initial+14);
 assert.equal(c("S.us.filter(u=>u.t===0&&['spear','xbow'].includes(u.k)&&u.o==='G'&&u.tg===tcOf(0)).length"),6,'the reserve guards the real home Town Centre');
 assert.equal(c('JSON.stringify(S.res[0])'),resources,'story reinforcements do not fabricate resources');
 assert.equal(c('S.over'),null,'royal reserves must not grant victory directly');
 c('cmpTick(2)');
 assert.equal(c("S.us.filter(u=>u.t===0&&['spear','xbow'].includes(u.k)).length"),initial+14,'no repeated reinforcements in a live mission');
 assert.equal(c('saveG()'),true);
 assert.equal(c('loadG()'),true);
 c('cmpTick(2)');
 assert.equal(c("S.us.filter(u=>u.t===0&&['spear','xbow'].includes(u.k)).length"),initial+14,'the reserve event persists across saves');
});
test('Tidewatch Castle breach sends a one-time Trebuchet column that still must damage the enemy capital',()=>{
 const c=tidewatch();
 const index=c("CAMP[14].ev.findIndex(e=>typeof e.do==='function'&&e.do.toString().includes('campaignTidewatchBreachColumn'))");
 assert.ok(index>=0,'a distinct Castle-breach assault event must be present');
 const oldUnits=c('S.us.length'),initialHealth=c('tcOf(1).hp');
 const stores=c('JSON.stringify(S.res[0])');
 c('cmp.k=14;cmpTick(5)');
 assert.equal(c('!!cmp.e['+index+']'),false,'the siege column cannot arrive before the Castle falls');
 c("S.bs.find(b=>b.t===1&&b.k==='castle').hp=0;cmp.k=14;cmpTick(1);cmpTick(1)");
 assert.equal(c('!!cmp.e['+index+']'),true);
 assert.equal(c("S.us.filter(u=>u.t===0&&u.k==='treb'&&u.hp>0).length"),2,'real artillery must spawn');
 assert.ok(c('S.us.length')>=oldUnits+12,'the full infantry escort and artillery must exist in the normal unit roster');
 assert.equal(c("S.us.filter(u=>u.t===0&&['knight','spear','xbow'].includes(u.k)&&u.o==='G'&&u.tg?.k==='treb').length"),10,'ten actual soldiers Guard the Trebuchets instead of racing ahead');
 assert.equal(c('JSON.stringify(S.res[0])'),stores,'the event must not hand over extra resources');
 assert.equal(c('tcOf(1).hp'),initialHealth,'the event must not directly damage the enemy capital');
 assert.equal(c('S.over'),null,'receiving reinforcements is not a win condition');
 const status=JSON.parse(c("JSON.stringify(S.us.filter(u=>u.t===0&&u.k==='treb').map(u=>({x:u.x,y:u.y,o:u.o,target:u.tg?.k,land:!S.wt[(u.y|0)*W+(u.x|0)],clear:!S.bs.some(b=>b.hp>0&&u.x>=b.x&&u.x<b.x+b.s&&u.y>=b.y&&u.y<b.y+b.s)})))"));
 assert.ok(status.every(u=>u.land&&u.clear),'siege pieces must spawn on unoccupied traversable land');
 assert.ok(status.every(u=>u.o==='a'&&u.target==='tc'),'siege pieces get an actual assault order to the enemy Town Centre');
 c('cmpTick(1)');
 assert.equal(c("S.us.filter(u=>u.t===0&&u.k==='treb'&&u.hp>0).length"),2,'no second detachment without a second Castle');
 assert.equal(c('saveG()'),true);
 assert.equal(c('loadG()'),true);
 c('cmpTick(1)');
 assert.equal(c("S.us.filter(u=>u.t===0&&u.k==='treb'&&u.hp>0).length"),2,'loaded games cannot duplicate siege reinforcements');
});
test('Tidewatch siege detachment joins after real Castle damage instead of waiting for the player army to collapse',()=>{
 const c=tidewatch();
 const id=c("CAMP[14].ev.findIndex(e=>typeof e.do==='function'&&e.do.toString().includes('campaignTidewatchBreachColumn'))");
 const full=c('B.castle.hp');
 c('S.bs.find(b=>b.t===1&&b.k===\'castle\').hp='+Math.round(full*.8)+';cmpTick(12)');
 assert.equal(c('!!cmp.e['+id+']'),false,'undamaged defences must not summon a forward assault');
 c('S.bs.find(b=>b.t===1&&b.k===\'castle\').hp='+Math.round(full*.7)+';cmpTick(1)');
 assert.equal(c('!!cmp.e['+id+']'),true,'Castle damaged by 30 percent earns a siege column');
 assert.equal(c("S.us.filter(u=>u.t===0&&u.k==='treb'&&u.hp>0).length"),2);
 assert.equal(c("S.bs.find(b=>b.t===1&&b.k==='castle').hp"),Math.round(full*.7),'allied arrivals must not destroy the Castle automatically');
 assert.equal(c('tcOf(1).hp'),900,'no instant enemy Town Centre damage');
 assert.equal(c('S.over'),null);
});
